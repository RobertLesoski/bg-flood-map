def speedup() -> bool:
    """Make cffi's type parsing ~50x faster for wgpu's ~13 000 typedefs.

    `Parser._parse` prepends one `typedef int NAME;` line per known typedef to EVERY parsed type string (so pycparser knows
    which identifiers are type names): 13 000 lines, ~35 ms per `ffi.new("WGPUxxx *")` the first time a type is used.  Only
    the identifiers that occur in the type string matter for parsing it, so the patched `_parse` shows pycparser just those
    (the full table is still used to resolve the parsed type).  Idempotent; returns True when the patch is active."""
    global _patched
    if _patched:
        return True
    try:
        import wgpu.backends.wgpu_native._api as api
        parser = api.ffi._parser
        orig = parser._parse
        ident = re.compile(r"[A-Za-z_]\w*")

        def fast_parse(csource):
            if not csource.startswith("void __dummy("):         # only the cheap type-string parses (cdef itself is untouched)
                return orig(csource)
            ids = set(ident.findall(csource))
            full = parser._declarations
            parser._declarations = {k: v for k, v in full.items() if not k.startswith("typedef ") or k[8:] in ids}
            try:
                return orig(csource)
            finally:
                parser._declarations = full
        parser._parse = fast_parse
        _patched = True
    except Exception:
        _patched = False
    return _patched


def warm() -> float:
    """Parse every type in TYPES; returns seconds spent (0.0 when the wgpu backend cannot be imported)."""
    t0 = time.perf_counter()
    speedup()
    try:
        import wgpu.backends.wgpu_native._api as api
        ffi = api.ffi
    except Exception:
        return 0.0
    for name in TYPES:
        try:
            ffi.typeof(name)
        except Exception:
            pass
    return time.perf_counter() - t0
