"""Instanced flow arrows on a camera-adaptive, world-anchored multi-resolution lattice.

Lattice: points at integer multiples of 2^j metres (j = -3 .. 12).  A point belongs to "level j" when j is the largest power
of two that divides both of its lattice coordinates, i.e. it is in lattices 2^k for every k <= j.  Each point decides for
itself whether it is drawn, from the screen-space spacing wanted AT THE POINT:
        L   = log2(D / ppm)        ppm = screen px per ground metre at the point's view depth, D = target spacing (px)
        w   = clamp(j - L + 1, 0, 1)
so around L = k exactly lattice 2^k is shown, the points that exist only in the finer lattice fade out as L rises
(cross-fade between the levels, no popping) and in a perspective view the near ground gets finer arrows than the far
ground, every arrow roughly D/2..D pixels from its neighbours.  Because the lattice is anchored in world space, panning
only changes weights.  The union of the levels at any L has the density of lattice 2^floor(L) (tested on the CPU:
`arrow_weight`).  Instances are generated by a compute shader (one thread per candidate point of every level, window of
N x N points around the eye per level; the window of level j is large enough for every point whose weight can be > 0) and
appended with an atomic counter; the draw is indirect.  Arrows are flat quads on the water surface (exaggerated Z),
oriented along the flow, length by speed (constant ON-SCREEN size, so no size popping), drawn with an analytic SDF
(shaft + head, dark outline, 1 px anti-aliasing), coloured by speed, lit slightly.  Only where depth >= 0.1 m and speed >= 0.05 m/s.
"""
from __future__ import annotations

import math

import numpy as np
import wgpu

from ..flowtex import COMMON_WGSL
from . import Layer
from . import fxcommon as fx

MAX_LEVELS = 16
J_MIN = -3
INST_BYTES = 32
ARGS_BYTES = 16
PARAM_BYTES = 48 + MAX_LEVELS * 16 + 16


# ============================================================================================ CPU logic (tested)
def arrow_weight(j: float, L: float) -> float:
    """Visibility weight of a level-j lattice point when the wanted spacing exponent at the point is L."""
    return min(max(j - L + 1.0, 0.0), 1.0)


def window_points(view_h_px: float, proj_f: float, spacing_px: float) -> int:
    """Lattice points per axis of one level's window: covers every point with weight > 0 (see module docstring)."""
    reach = 1.35 * (proj_f * view_h_px * 0.5) * 2.0 / spacing_px          # horizontal reach in lattice units of level j
    return int(math.ceil(2.0 * reach)) + 3


def level_range(spacing_px: float, proj_f: float, view_h_px: float, eye_height: float, pitch_deg: float, fov_rad: float,
                max_dist: float, n_window: int) -> tuple[int, int]:
    """(j_min, j_max): finest level needed for the nearest visible ground, coarsest level whose window reaches `max_dist`."""
    ang = min(math.radians(pitch_deg) + fov_rad * 0.5, math.pi * 0.5)
    w_min = max(eye_height, 0.5) / max(math.sin(ang), 0.05) * math.cos(fov_rad * 0.5)
    ppm = proj_f * view_h_px * 0.5 / max(w_min, 0.3)
    j_min = int(math.floor(math.log2(spacing_px / ppm))) - 1
    j_min = max(J_MIN, j_min)
    j_max = int(math.ceil(math.log2(max(max_dist, 1.0) / (n_window * 0.5))))
    j_max = min(max(j_max, j_min), J_MIN + MAX_LEVELS - 1)
    return j_min, j_max


def level_windows(eye_x: float, eye_y: float, j_min: int, j_max: int, n_window: int):
    """[(j, ix0, iy0, top)] lattice-index origin of every level's window, centred on the eye and aligned to the lattice."""
    out = []
    for j in range(j_min, j_max + 1):
        s = 2.0 ** j
        out.append((j, int(math.floor(eye_x / s)) - n_window // 2, int(math.floor(eye_y / s)) - n_window // 2,
                    1 if j == j_max else 0))
    return out


# ============================================================================================ WGSL
PARAMS_WGSL = """
struct Params {
  a: vec4<f32>,   // spacing px D, size scale, min depth, min speed
  b: vec4<f32>,   // speed for full size, alpha, colour mode, instance cap
  c: vec4<f32>,   // lift (m), 0, 0, 0
  lv: array<vec4<i32>, 16>,   // per level slot: j, ix0, iy0, top flag
  n: vec4<u32>,   // window points per axis, number of levels, 0, 0
};
struct Inst { pos: vec2<f32>, ang: f32, z: f32, speed: f32, alpha: f32, len: f32, mpp: f32 };
@group(1) @binding(0) var<uniform> AP: Params;
"""

COMPUTE_WGSL = COMMON_WGSL + fx.FX_WGSL + PARAMS_WGSL + """
struct Args { vcount: u32, icount: atomic<u32>, first_v: u32, first_i: u32 };
@group(1) @binding(1) var<storage, read_write> insts: array<Inst>;
@group(1) @binding(2) var<storage, read_write> args: Args;

@compute @workgroup_size(1)
fn cs_reset() {
  args.vcount = 6u;
  atomicStore(&args.icount, 0u);
  args.first_v = 0u;
  args.first_i = 0u;
}

@compute @workgroup_size(8, 8, 1)
fn cs_gen(@builtin(global_invocation_id) gid: vec3<u32>) {
  let n = AP.n.x;
  if (gid.x >= n || gid.y >= n || gid.z >= AP.n.y) { return; }
  let lv = AP.lv[gid.z];
  let ix = lv.y + i32(gid.x);
  let iy = lv.z + i32(gid.y);
  if (lv.w == 0 && ((ix | iy) & 1) == 0) { return; }          // belongs to the next coarser level
  let s = exp2(f32(lv.x));
  let p = vec2<f32>(f32(ix), f32(iy)) * s;
  if (abs(p.x) > frame.grid.x * 0.5 || abs(p.y) > frame.grid.y * 0.5) { return; }
  let fl = flow_at(world_to_uv(p));
  let speed = length(fl.vel);
  if (fl.valid < 0.5 || fl.depth < AP.a.z || speed < AP.a.w) { return; }
  let z = ground_height(p) * frame.grid.w + fl.depth * frame.enc.w;
  let c = frame.view_proj * vec4<f32>(p, z, 1.0);
  if (c.w < 0.3) { return; }
  if (abs(c.x) > c.w * 1.08 || abs(c.y) > c.w * 1.08) { return; }
  let ppm = px_per_m_at(c.w);
  let L = log2(AP.a.x / ppm);
  let wl = clamp(f32(lv.x) - L + 1.0, 0.0, 1.0);
  if (wl < 0.02) { return; }
  let alpha = smoothstep(0.0, 1.0, wl) * smoothstep(0.1, 0.25, fl.depth) * smoothstep(0.05, 0.12, speed);
  let len_px = 0.5 * AP.a.x * AP.a.y * (0.42 + 0.58 * smoothstep(0.05, AP.b.x, speed));
  let idx = atomicAdd(&args.icount, 1u);
  if (f32(idx) >= AP.b.w) { return; }
  var o: Inst;
  o.pos = p;
  o.ang = atan2(fl.vel.y, fl.vel.x);
  o.z = z;
  o.speed = speed;
  o.alpha = alpha;
  o.len = len_px / ppm;
  o.mpp = 1.0 / ppm;
  insts[idx] = o;
}
"""

RENDER_WGSL = COMMON_WGSL + fx.FX_WGSL + PARAMS_WGSL + """
@group(1) @binding(1) var<storage, read> insts: array<Inst>;

struct VOut {
  @builtin(position) pos: vec4<f32>,
  @location(0) loc: vec2<f32>,
  @location(1) @interpolate(flat) len: f32,
  @location(2) @interpolate(flat) mpp: f32,
  @location(3) @interpolate(flat) speed: f32,
  @location(4) @interpolate(flat) alpha: f32,
  @location(5) wz: f32,
};

@vertex fn vs(@builtin(vertex_index) vi: u32, @builtin(instance_index) ii: u32) -> VOut {
  var o: VOut;
  o.pos = vec4<f32>(0.0, 0.0, 2.0, 1.0);
  o.loc = vec2<f32>(0.0);
  o.len = 1.0; o.mpp = 1.0; o.speed = 0.0; o.alpha = 0.0; o.wz = 0.0;
  if (f32(ii) >= AP.b.w) { return o; }
  let a = insts[ii];
  var cs = array<vec2<f32>, 6>(vec2<f32>(-1.0, -1.0), vec2<f32>(1.0, -1.0), vec2<f32>(1.0, 1.0),
                               vec2<f32>(-1.0, -1.0), vec2<f32>(1.0, 1.0), vec2<f32>(-1.0, 1.0));
  let q = cs[vi];
  let hx = 0.5 * a.len + 1.6 * a.mpp;
  let hy = 0.21 * a.len + 1.6 * a.mpp;
  let d = vec2<f32>(cos(a.ang), sin(a.ang));
  let pr = vec2<f32>(-d.y, d.x);
  let l = vec2<f32>(q.x * hx, q.y * hy);
  let w = a.pos + d * l.x + pr * l.y;
  let c0 = frame.view_proj * vec4<f32>(a.pos, a.z, 1.0);
  let lift = AP.c.x + c0.w * 5.0e-4;
  o.pos = frame.view_proj * vec4<f32>(w, a.z + lift, 1.0);
  o.loc = l;
  o.len = a.len;
  o.mpp = a.mpp;
  o.speed = a.speed;
  o.alpha = a.alpha;
  o.wz = c0.w;
  return o;
}

fn sd_box(p: vec2<f32>, c: vec2<f32>, h: vec2<f32>) -> f32 {
  let q = abs(p - c) - h;
  return length(max(q, vec2<f32>(0.0))) + min(max(q.x, q.y), 0.0);
}

@fragment fn fs(in: VOut) -> @location(0) vec4<f32> {
  let len = in.len;
  let hl = 0.5 * len;
  let head_len = 0.42 * len;
  let head_w = 0.21 * len;
  let shaft_w = max(0.065 * len, 0.9 * in.mpp);
  let p = in.loc;
  // shaft
  let x0 = -hl;
  let x1 = hl - head_len + 0.04 * len;
  let d_shaft = sd_box(p, vec2<f32>((x0 + x1) * 0.5, 0.0), vec2<f32>((x1 - x0) * 0.5, shaft_w));
  // head (convex: max of three half-plane distances)
  let nrm = normalize(vec2<f32>(head_w, head_len));
  let tip = vec2<f32>(hl, 0.0);
  let d_back = (hl - head_len) - p.x;
  let d_up = dot(vec2<f32>(p.x - tip.x, p.y), nrm);
  let d_dn = dot(vec2<f32>(p.x - tip.x, -p.y), nrm);
  let d_head = max(d_back, max(d_up, d_dn));
  let d = min(d_shaft, d_head) / in.mpp;                    // signed distance in pixels
  let fill = clamp(0.5 - d, 0.0, 1.0);
  let rim = clamp(0.5 - (d - 1.1), 0.0, 1.0);
  var col = speed_ramp(in.speed * 1.15);
  var rim_col = vec3<f32>(0.02, 0.07, 0.14);
  let mode = u32(AP.b.z + 0.5);
  if (mode == 1u) { col = vec3<f32>(0.97, 0.99, 1.0); }
  if (mode == 2u) { col = vec3<f32>(0.04, 0.10, 0.20); rim_col = vec3<f32>(0.95, 0.98, 1.0); }
  let lit = 0.78 + 0.22 * clamp(frame.sun.z * frame.sun.w, 0.0, 1.0);
  col = col * lit;
  let cover = max(fill, rim * 0.62);
  if (cover <= 0.003) { discard; }
  let rgb = mix(rim_col, col, fill / max(cover, 1e-3));
  let a = cover * in.alpha * AP.b.y;
  return vec4<f32>(rgb * a, a);
}
"""


class ArrowsLayer(Layer):
    name = "arrows"
    title = "Flow arrows"
    has_ui = True
    default_enabled = True

    COLOURS = ("Speed", "White", "Dark")

    def __init__(self):
        self.spacing_px = 60.0           # target spacing D: the dominant lattice is D/2 .. D px apart
        self.size = 1.0
        self.alpha = 0.95
        self.colour = 0
        self.full_speed = 2.0            # m/s at which the arrow reaches full length
        self.min_depth = 0.1
        self.min_speed = 0.05
        self.max_instances = 30_000
        self.params = None
        self.n_levels = 0
        self.n_window = 0
        self.level_info = (0, 0)
        self._cap = 30_000

    # ------------------------------------------------------------------------------------------ lifecycle
    def init(self, app):
        dev = app.ctx.device
        vis_c = wgpu.ShaderStage.COMPUTE
        vis_r = wgpu.ShaderStage.VERTEX | wgpu.ShaderStage.FRAGMENT
        self.params = dev.create_buffer(label="arrow-params", size=PARAM_BYTES,
                                        usage=wgpu.BufferUsage.UNIFORM | wgpu.BufferUsage.COPY_DST)
        cap = 30_000
        self.buf = dev.create_buffer(label="arrow-instances", size=cap * INST_BYTES,
                                     usage=wgpu.BufferUsage.STORAGE | wgpu.BufferUsage.COPY_SRC)
        self.args = dev.create_buffer(label="arrow-args", size=ARGS_BYTES,
                                      usage=wgpu.BufferUsage.STORAGE | wgpu.BufferUsage.INDIRECT | wgpu.BufferUsage.COPY_SRC
                                      | wgpu.BufferUsage.COPY_DST)
        app.ctx.queue.write_buffer(self.args, 0, np.array([6, 0, 0, 0], np.uint32))
        app.ctx.track("arrows", cap * INST_BYTES)
        bgl_c = dev.create_bind_group_layout(label="arrows-compute-bgl", entries=[
            {"binding": 0, "visibility": vis_c | vis_r, "buffer": {"type": "uniform"}},
            {"binding": 1, "visibility": vis_c, "buffer": {"type": "storage"}},
            {"binding": 2, "visibility": vis_c, "buffer": {"type": "storage"}}])
        bgl_r = dev.create_bind_group_layout(label="arrows-render-bgl", entries=[
            {"binding": 0, "visibility": vis_c | vis_r, "buffer": {"type": "uniform"}},
            {"binding": 1, "visibility": wgpu.ShaderStage.VERTEX, "buffer": {"type": "read-only-storage"}}])
        self.bg_c = dev.create_bind_group(label="arrows-compute-bg", layout=bgl_c, entries=[
            {"binding": 0, "resource": {"buffer": self.params, "offset": 0, "size": PARAM_BYTES}},
            {"binding": 1, "resource": {"buffer": self.buf, "offset": 0, "size": cap * INST_BYTES}},
            {"binding": 2, "resource": {"buffer": self.args, "offset": 0, "size": ARGS_BYTES}}])
        self.bg_r = dev.create_bind_group(label="arrows-render-bg", layout=bgl_r, entries=[
            {"binding": 0, "resource": {"buffer": self.params, "offset": 0, "size": PARAM_BYTES}},
            {"binding": 1, "resource": {"buffer": self.buf, "offset": 0, "size": cap * INST_BYTES}}])
        cmod = dev.create_shader_module(label="arrows-compute", code=COMPUTE_WGSL)
        pl_c = dev.create_pipeline_layout(bind_group_layouts=[app.frame.layout, bgl_c])
        self.pipe_reset = dev.create_compute_pipeline(label="arrows-reset", layout=pl_c,
                                                      compute={"module": cmod, "entry_point": "cs_reset"})
        self.pipe_gen = dev.create_compute_pipeline(label="arrows-gen", layout=pl_c,
                                                    compute={"module": cmod, "entry_point": "cs_gen"})
        rmod = dev.create_shader_module(label="arrows-render", code=RENDER_WGSL)
        pl_r = dev.create_pipeline_layout(bind_group_layouts=[app.frame.layout, bgl_r])
        blend = {"color": {"src_factor": "one", "dst_factor": "one-minus-src-alpha", "operation": "add"},
                 "alpha": {"src_factor": "one", "dst_factor": "one-minus-src-alpha", "operation": "add"}}
        self.pipe_draw = dev.create_render_pipeline(
            label="arrows-draw", layout=pl_r, vertex={"module": rmod, "entry_point": "vs"},
            primitive={"topology": "triangle-list", "cull_mode": "none"},
            depth_stencil={"format": app.depth_format, "depth_write_enabled": False, "depth_compare": "greater"},
            multisample={"count": app.sample_count},
            fragment={"module": rmod, "entry_point": "fs", "targets": [{"format": app.colour_format, "blend": blend}]})

    def shutdown(self, app):
        for b in (getattr(self, "buf", None), getattr(self, "args", None), self.params):
            try:
                if b is not None:
                    b.destroy()
            except Exception:
                pass
        app.ctx.untrack("arrows")

    # ------------------------------------------------------------------------------------------ per frame
    def update(self, app, dt):
        cam = app.camera
        pw, ph = app._target_size if app._target_size != (0, 0) else (1920, 1080)
        f = 1.0 / math.tan(cam.fov * 0.5)
        n = window_points(ph, f, self.spacing_px)
        eye = cam.eye()
        eye_h = max(float(eye[2]) - cam.ground_z(eye[0], eye[1]), 1.0)
        fr = app.terrain.frame
        sx, sy = fr.size_m
        corner = max(math.hypot(abs(eye[0]) + sx * 0.5, abs(eye[1]) + sy * 0.5), 200.0)
        j0, j1 = level_range(self.spacing_px, f, ph, eye_h, cam.pitch, cam.fov, corner, n)
        wins = level_windows(float(eye[0]), float(eye[1]), j0, j1, n)
        self.n_window, self.n_levels, self.level_info = n, len(wins), (j0, j1)
        cap = min(self.max_instances, self._cap)
        q = fx.quality_name(app)
        if q is not None:
            cap = min(cap, fx.QUALITY[q]["arrows"])
        buf = np.zeros(PARAM_BYTES // 4, np.float32)
        buf[0:4] = (self.spacing_px, self.size, self.min_depth, self.min_speed)
        buf[4:8] = (self.full_speed, self.alpha, self.colour, cap)
        buf[8:12] = (0.14, 0.0, 0.0, 0.0)
        lv = np.zeros((MAX_LEVELS, 4), np.int32)
        for i, w in enumerate(wins):
            lv[i] = w
        buf[12:12 + MAX_LEVELS * 4] = lv.reshape(-1).view(np.float32)
        un = buf[12 + MAX_LEVELS * 4:].view(np.uint32)
        un[0], un[1] = n, len(wins)
        app.ctx.queue.write_buffer(self.params, 0, buf)

    def compute(self, app, enc):
        cp = enc.begin_compute_pass(label="arrows")
        cp.set_bind_group(0, app.frame.bind_group)
        cp.set_bind_group(1, self.bg_c)
        cp.set_pipeline(self.pipe_reset)
        cp.dispatch_workgroups(1)
        cp.set_pipeline(self.pipe_gen)
        g = (self.n_window + 7) // 8
        cp.dispatch_workgroups(g, g, max(self.n_levels, 1))
        cp.end()

    def draw(self, app, pass_):
        pass_.set_pipeline(self.pipe_draw)
        pass_.set_bind_group(0, app.frame.bind_group)
        pass_.set_bind_group(1, self.bg_r)
        pass_.draw_indirect(self.args, 0)

    def read_count(self, app) -> int:
        """Synchronous read-back of the number of generated arrows (tests / tools)."""
        app.ctx.sync()
        a = np.frombuffer(app.ctx.queue.read_buffer(self.args, 0, ARGS_BYTES), np.uint32)
        return int(a[1])

    # ------------------------------------------------------------------------------------------ UI / state
    def ui(self, app):
        from imgui_bundle import imgui
        imgui.set_next_item_width(-120)
        ch, v = imgui.slider_float("Spacing (px)", self.spacing_px, 40.0, 200.0, "%.0f")
        if ch:
            self.spacing_px = v
        imgui.set_next_item_width(-120)
        ch, v = imgui.slider_float("Arrow size", self.size, 0.4, 2.0, "%.2f x")
        if ch:
            self.size = v
        imgui.set_next_item_width(-120)
        ch, v = imgui.slider_float("Opacity##a", self.alpha, 0.1, 1.0, "%.2f")
        if ch:
            self.alpha = v
        imgui.set_next_item_width(-120)
        ch, v = imgui.slider_float("Full length at (m/s)", self.full_speed, 0.5, 4.0, "%.1f")
        if ch:
            self.full_speed = v
        imgui.set_next_item_width(-120)
        ch, i = imgui.combo("Colour by##a", self.colour, list(self.COLOURS))
        if ch:
            self.colour = i
        imgui.text_disabled(f"lattice levels 2^{self.level_info[0]} .. 2^{self.level_info[1]} m, max {self._cap // 1000}k arrows")

    def save_state(self):
        return {"spacing_px": self.spacing_px, "size": self.size, "alpha": self.alpha, "colour": self.colour,
                "full_speed": self.full_speed}

    def load_state(self, d):
        self.spacing_px = float(d.get("spacing_px", self.spacing_px))
        self.size = float(d.get("size", self.size))
        self.alpha = float(d.get("alpha", self.alpha))
        self.colour = int(d.get("colour", self.colour))
        self.full_speed = float(d.get("full_speed", self.full_speed))
